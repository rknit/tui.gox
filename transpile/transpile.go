// CollectSignatures extracts top-level component signatures from Go source:
// functions returning a Node with zero parameters or exactly one parameter.
func CollectSignatures(src []byte, into map[string]Signature) {
	fset := token.NewFileSet()
	f, _ := parser.ParseFile(fset, "", src, parser.SkipObjectResolution)
	if f == nil {
		return
	}
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Recv != nil || fd.Type.Results == nil || len(fd.Type.Results.List) != 1 || strings.HasPrefix(fd.Name.Name, nodeBody) {
			continue
		}
		res := fd.Type.Results.List[0].Type
		if !strings.HasSuffix(string(src[fset.Position(res.Pos()).Offset:fset.Position(res.End()).Offset]), "Node") {
			continue
		}
		var tparams []string
		if fd.Type.TypeParams != nil {
			for _, f := range fd.Type.TypeParams.List {
				for _, n := range f.Names {
					tparams = append(tparams, n.Name)
				}
			}
		}
		params := fd.Type.Params.List
		switch {
		case len(params) == 0:
			into[fd.Name.Name] = Signature{NoProps: true, TypeParams: tparams}
		case len(params) == 1 && len(params[0].Names) <= 1:
			typ := params[0].Type
			into[fd.Name.Name] = Signature{TypeParams: tparams, PropsType: string(src[fset.Position(typ.Pos()).Offset:fset.Position(typ.End()).Offset])}
		}
	}
}

// splitTopLevel splits a comma separated list, ignoring nested brackets.
func splitTopLevel(s string) []string {
	var out []string
	depth, start := 0, 0
	for i, c := range s {
		switch c {
		case '[', '(', '{':
			depth++
		case ']', ')', '}':
			depth--
		case ',':
			if depth == 0 {
				out = append(out, strings.TrimSpace(s[start:i]))
				start = i + 1
			}
		}
	}
	return append(out, strings.TrimSpace(s[start:]))
}

// substitute replaces type parameter identifiers in typ with arguments.
func substitute(typ string, params, args []string) string {
	repl := map[string]string{}
	for i, p := range params {
		repl[p] = args[i]
	}
	var b strings.Builder
	src := []byte(typ)
	for i := 0; i < len(src); {
		if isIdentStart(src, i) && (i == 0 || src[i-1] != '.') {
			e := identEnd(src, i)
			if r, ok := repl[string(src[i:e])]; ok {
				b.WriteString(r)
			} else {
				b.Write(src[i:e])
			}
			i = e
			continue
		}
		b.WriteByte(src[i])
		i++
	}
	return b.String()
}

// ---------------------------------------------------------------------------
// Source maps
//
// Generated strings carry invisible markers (private-use runes) around
// fragments that correspond to source ranges. strip removes them at the end
// and records the final offsets, so nested generation needs no bookkeeping.

const (
	markOpen  = ""
	markID    = ""
	markClose = ""
)

type markSrc struct {
	src, n int
	weak   bool // loses ties against other segments for the same source
}

type alias struct{ src, n, id int }

// Segment relates a source range to a generated range.
type Segment struct {
	Src, SrcLen int
	Dst, DstLen int
}

// SourceMap relates byte offsets of a .gox file and its generated Go code.
type SourceMap struct {
	Segments []Segment
}

func pickSegment(segs []Segment, off int, from, to func(Segment) (int, int)) (int, bool) {
	best, bestLen := -1, 0
	for i, sg := range segs {
		s, n := from(sg)
		if off < s || off > s+n {
			continue
		}
		if best < 0 || n <= bestLen {
			best, bestLen = i, n
		}
	}
	if best < 0 {
		return 0, false
	}
	s, n := from(segs[best])
	d, dn := to(segs[best])
	switch {
	case n == dn:
		return d + off - s, true
	case off == s+n:
		return d + dn, true
	}
	return d, true
}

func srcSide(s Segment) (int, int) { return s.Src, s.SrcLen }
func dstSide(s Segment) (int, int) { return s.Dst, s.DstLen }

// ToGenerated maps a source offset to a generated offset.
func (m *SourceMap) ToGenerated(off int) (int, bool) {
	return pickSegment(m.Segments, off, srcSide, dstSide)
}

// ToSource maps a generated offset to a source offset.
func (m *SourceMap) ToSource(off int) (int, bool) {
	return pickSegment(m.Segments, off, dstSide, srcSide)
}

// mark wraps generated code s that corresponds to src[pos:pos+n].
func (t *transpiler) mark(pos, n int, s string) string {
	id := len(t.marks)
	t.marks = append(t.marks, markSrc{src: pos, n: n})
	return markOpen + strconv.Itoa(id) + markID + s + markClose
}

// markWeak is like mark, but when mapping source offsets to generated ones,
// other segments of the same source range win over this one.
func (t *transpiler) markWeak(pos, n int, s string) string {
	t.marks = append(t.marks, markSrc{pos, n, true})
	return markOpen + strconv.Itoa(len(t.marks)-1) + markID + s + markClose
}

// markTag marks the identifier part of a component reference with the tag
// name position, and records the closing tag name as an alias of it.
func (t *transpiler) markTag(fn, tag string, pos, closePos int) string {
	prefix, ident := "", fn
	if !strings.Contains(tag, ".") && strings.HasPrefix(fn, t.rt+".") {
		prefix, ident = t.rt+".", fn[len(t.rt)+1:]
	}
	id := len(t.marks)
	out := prefix + t.mark(pos, len(tag), ident)
	if closePos >= 0 {
		t.aliases = append(t.aliases, alias{closePos, len(baseOf(tag)), id})
	}
	return out
}

func (t *transpiler) openRun(out *strings.Builder, pos int) int {
	id := len(t.marks)
	t.marks = append(t.marks, markSrc{src: pos})
	out.WriteString(markOpen + strconv.Itoa(id) + markID)
	return id
}

func (t *transpiler) closeRun(out *strings.Builder, id, pos int) {
	t.marks[id].n = pos - t.marks[id].src
	out.WriteString(markClose)
}

// unmark removes markers from s.
func unmark(s string) string {
	if !strings.Contains(s, markOpen) {
		return s
	}
	var b strings.Builder
	for i := 0; i < len(s); {
		switch {
		case strings.HasPrefix(s[i:], markOpen):
			i += strings.Index(s[i:], markID) + len(markID)
		case strings.HasPrefix(s[i:], markClose):
			i += len(markClose)
		default:
			b.WriteByte(s[i])
			i++
		}
	}
	return b.String()
}

// strip removes markers and returns the clean code with its segments.
func (t *transpiler) strip(s string) (string, []Segment) {
	var b strings.Builder
	b.Grow(len(s))
	type open struct{ id, at int }
	var stack []open
	var segs, weak []Segment
	byID := map[int]Segment{}
	for i := 0; i < len(s); {
		switch {
		case strings.HasPrefix(s[i:], markOpen):
			j := strings.Index(s[i:], markID)
			id, _ := strconv.Atoi(s[i+len(markOpen) : i+j])
			stack = append(stack, open{id, b.Len()})
			i += j + len(markID)
		case strings.HasPrefix(s[i:], markClose):
			o := stack[len(stack)-1]
			stack = stack[:len(stack)-1]
			m := t.marks[o.id]
			sg := Segment{Src: m.src, SrcLen: m.n, Dst: o.at, DstLen: b.Len() - o.at}
			byID[o.id] = sg
			switch {
			case m.weak:
				weak = append(weak, sg)
			case sg.SrcLen > 0 || sg.DstLen > 0:
				segs = append(segs, sg)
			}
			i += len(markClose)
		default:
			b.WriteByte(s[i])
			i++
		}
	}
	// Aliases and weak segments go first so that they lose ties against
	// equally specific segments (later segments win ties): generated offsets
	// map back to the opening tag, and source offsets avoid weak targets.
	aliased := weak
	for _, a := range t.aliases {
		if sg, ok := byID[a.id]; ok {
			aliased = append(aliased, Segment{Src: a.src, SrcLen: a.n, Dst: sg.Dst, DstLen: sg.DstLen})
		}
	}
	return b.String(), append(aliased, segs...)
}
